import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const day=d=>[d.getFullYear(),String(d.getMonth()+1).padStart(2,'0'),String(d.getDate()).padStart(2,'0')].join('-');
const past=new Date();past.setDate(past.getDate()-1);
const fixture={version:4,clients:[{id:'mobile-client',name:'Example client',currentRequestId:'req-1',requests:[{id:'req-1',title:'Example request',status:'active',situations:[{id:'sit-1',name:'Example situation',level:5,beliefs:[{id:'b-1',text:'Example belief',level:6,feelings:[]}]}]}],sessions:[],questionnaires:[],quickNotes:[]}],calendarEvents:[{id:'rem-1',clientId:'mobile-client',type:'Напоминание',title:'Example reminder',date:day(past),time:'09:00'}]};
const browser=await chromium.launch({headless:true});
try{
 const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true,locale:'ru-RU'});
 const page=await context.newPage();
 await page.addInitScript(data=>{localStorage.setItem('diagnostika-web-v1',JSON.stringify(data));localStorage.setItem('diagnostika-ui-language','ru')},fixture);
 await page.goto('http://127.0.0.1:8137/index.html',{waitUntil:'domcontentloaded'});
 await page.locator('#mobileBottomNav').waitFor({state:'visible',timeout:35000});
 const fits=()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2);
 assert(await fits(),'Mobile body overflows');
 assert(await page.locator('#hdHomeView').isVisible());
 assert(!(await page.locator('.hd-sidebar').isVisible()));
 assert(await page.locator('#settingsMenuBtn').isVisible());
 await page.locator('[data-action="attention"]').click();
 assert(await page.locator('#hwsAttentionList').isVisible());
 assert((await page.locator('#hwsAttentionList').innerText()).includes('Example reminder'));
 await page.locator('#mobileBottomNav [data-mobile-action="clients"]').click();
 assert(await page.locator('.hd-sidebar').isVisible());
 assert(!(await page.locator('.hd-main').isVisible()));
 await page.locator('.hd-client-row[data-id="mobile-client"]').click();
 assert(await page.locator('#hdClientView').isVisible());
 assert(!(await page.locator('.hd-sidebar').isVisible()));
 assert(await fits(),'Client view overflows');
 await page.evaluate(()=>{const s=window.DiagnostikaPlatform.shell;s.viewRequest('req-1');s.selectSituation('sit-1');s.setMode('diagnosis');s.renderMode();});
 await page.locator('#mobileDiagnosisTabs').waitFor({state:'visible'});
 assert(await page.locator('#diagnosisWorkspace>.left-panel').isVisible());
 await page.locator('#mobileDiagnosisTabs [data-mobile-action="tree"]').click();
 await page.locator('#tree .tree-row[data-element-id="b-1"]').click();
 assert(await page.locator('#rightPanel').isVisible());
 assert(!(await page.locator('#centerPanel').isVisible()));
 assert(await fits(),'Diagnosis view overflows');
 await page.locator('#mobileBottomNav [data-mobile-action="home"]').click();
 await page.locator('#hdHomeView').waitFor({state:'visible'});
 await page.locator('#mobileBottomNav [data-mobile-action="calendar"]').click();
 await page.locator('.cal-overlay[open]').waitFor({state:'visible'});
 await page.locator('.cal-close').click();
 await page.locator('#mobileBottomNav [data-mobile-action="notes"]').click();
 await page.locator('.quick-notes-overlay:not([hidden])').waitFor({state:'visible'});
 await page.locator('.quick-notes-close').click();
 await page.evaluate(()=>window.DiagnostikaI18n.setLanguage('en'));
 await page.waitForFunction(()=>document.querySelector('#mobileBottomNav [data-mobile-action="home"]').textContent.includes('Home'));
 await context.close();
 const desktop=await browser.newPage({viewport:{width:1440,height:900}});
 await desktop.goto('http://127.0.0.1:8137/index.html',{waitUntil:'domcontentloaded'});
 await desktop.locator('#hdHomeView').waitFor({state:'visible',timeout:35000});
 assert(!(await desktop.locator('#mobileBottomNav').isVisible()));
 assert(await desktop.locator('.hd-sidebar').isVisible());
 console.log('MOBILE_WORKSPACE_BROWSER_OK');
}finally{await browser.close();}
