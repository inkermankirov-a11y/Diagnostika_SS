import assert from 'node:assert/strict';
import fs from 'node:fs';
const base=new URL('../',import.meta.url);
const get=p=>fs.readFileSync(new URL(p,base),'utf8');
const service=get('server/accounts/service.py');
const html=get('server/accounts/index.html');
const ui=get('server/accounts/ui.js');
const about=get('about-program.js');
const archive=JSON.parse(get('server/accounts/legal-archive/license-1.0.json'));
const license=html.match(/<article id="licenseDocument" class="legal-document" hidden>([\s\S]*?)<\/article>/)?.[1];
assert(license,'license document missing');
const titles=[...license.matchAll(/<(?:h2|h3|p)\b[^>]*>([\s\S]*?)<\/(?:h2|h3|p)>/g)].map(m=>m[1].replace(/<[^>]*>/g,''));
assert.equal(titles.length,39);
assert(titles[0].includes('1.1'));
assert(titles[10].startsWith('3.2.')&&titles[10].includes('FREE')&&titles[10].includes('HCS')&&titles[10].includes('STANDARD')&&titles[10].includes('VIP'));
for(const value of ['399 ₽','2 388 ₽','5 USD','30 USD','шесть календарных месяцев','один календарный месяц','досрочное продление'])assert(titles[10].includes(value),'missing '+value);
assert(titles[14].startsWith('4.2.')&&titles[14].includes('не шифруются'));
assert(titles[34].startsWith('9.2.')&&titles[34].includes('не изменяет ранее заключённые договоры'));
assert(about.includes('Лицензия и условия использования')&&!about.includes('Программу разрешается бесплатно использовать'));
assert(about.includes('получения')===false||about.includes('HCS'));
assert.equal(archive.versions[0],'1.0');
assert(archive.license_html_ru.includes('редакция 1.0'));
assert.equal(Object.keys(archive.translations).length,4);
assert(archive.hcs_clause.ru.includes('HypnoCoaching Student'));
assert(service.includes('LEGAL_VERSION="1.1"')&&!service.includes('LEGAL_VERSION="1.0"'));
assert(service.includes('ORDER BY accepted_at DESC,rowid DESC LIMIT 1'));
assert(!service.includes('legal_acceptance WHERE user_id=? AND version IN'));
assert(ui.includes("currentUser?.legal_version!=='1.1-hcs'"));
assert(ui.includes("title.textContent.replace('1.1','1.1-hcs')"));
assert(ui.includes("data.legal_version=currentUser?.legal_version||'1.1'"));
const trans=JSON.parse(ui.match(/const accountLegalTranslations=(\{[\s\S]*?\});\nconst legalOriginals/)[1]);
for(const [lang,parts] of Object.entries(trans)){
 const x=parts[0];assert.equal(x.length,39,lang);
 assert(x[0].includes('1.1')&&x[10].includes('FREE')&&x[10].includes('STANDARD')&&x[10].includes('HCS')&&x[10].includes('VIP'),lang);
 assert(x[10].includes('399')&&x[10].includes('2.388')||x[10].includes('2,388')||x[10].includes('2 388'),lang);
 assert(x[14].startsWith('4.2.')&&x[34].startsWith('9.2.'),lang);
}
assert(html.includes('ui.js?v=20261124-license-manager-2'));
assert(get('index.html').includes('about-program.js?v=20261123-license-1-1'));
console.log('PASS: versions 1.1 and 1.1-hcs, all 5 language variants, tariff clauses, historic archive, prior consents and no notification gate');
