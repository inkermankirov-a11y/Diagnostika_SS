function fallbackStrongVu(data){
  const groups=new Map();
  for(const situation of Array.isArray(data.ситуации)?data.ситуации:[]){
    for(const belief of Array.isArray(situation.первичные_убеждения)?situation.первичные_убеждения:[]){
      const primary=clean(belief?.убеждение);
      if(!primary)continue;
      for(const feeling of Array.isArray(belief.вторичные_чувства)?belief.вторичные_чувства:[]){
        const feelingText=clean(feeling?.чувство_или_реакция);
        if(!feelingText)continue;
        for(const deep of Array.isArray(feeling.вторичные_убеждения)?feeling.вторичные_убеждения:[]){
          const vu=clean(deep?.убеждение_или_самоопределение);
          const key=normalizeVu(vu);
          if(!key)continue;
          const level=Math.max(1,Math.min(10,Number(deep?.уровень)||5));
          const group=groups.get(key)||{убеждение:vu,максимальный_уровень:0,повторений:0,ветки:[]};
          if(level>=group.максимальный_уровень)group.убеждение=vu;
          group.максимальный_уровень=Math.max(group.максимальный_уровень,level);
          group.повторений++;
          group.ветки.push({
            ситуация:clean(situation?.ситуация),
            первичное_убеждение:primary,
            вторичное_чувство:feelingText,
            уровень_ВУ:level,
            реакции:(Array.isArray(deep?.инстинктивные_реакции)?deep.инстинктивные_реакции:[])
              .map(x=>clean(x?.реакция)).filter(Boolean)
          });
          groups.set(key,group);
        }
      }
    }
  }
  return [...groups.values()]
    .filter(x=>x.максимальный_уровень>=6)
    .sort((a,b)=>(b.повторений>1)-(a.повторений>1)||b.повторений-a.повторений||b.максимальный_уровень-a.максимальный_уровень);
}

const source=Array.isArray(diagnosticData.сильные_ВУ)
